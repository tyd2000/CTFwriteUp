def nCr_mod_prime(n, r, p):
    if r < 0 or r > n:
        return 0
    # Lucas 定理
    res = 1
    while n or r:
        ni = n % p
        ri = r % p
        if ri > ni:
            return 0
        # 计算 C(ni, ri) mod p
        num = fact[ni]
        den = (fact[ri] * fact[ni - ri]) % p
        comb = (num * modinv(den, p)) % p
        res = (res * comb) % p
        n //= p
        r //= p
    return res

